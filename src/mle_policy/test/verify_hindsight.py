"""Verify hindsight-only journals, source provenance, and downstream readers."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from src.mle_policy.src.data.big_journal import iter_samples as iter_big_samples
from src.mle_policy.src.data.journal import iter_samples, read_nodes, read_run_meta
from src.mle_policy.src.data.hindsight.helper import VERSION, atomic_json, parts
from src.mle_policy.src.data.hindsight.regenerate import inject_hint
from src.mle_policy.src.data.hindsight.tree import better, episodes, prune, validate


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def verify_journal(source: Path, output: Path, relative: Path) -> dict:
    source_path, output_path = source / relative, output / relative
    original = {
        row["data"]["step"]: row["data"]
        for row in (json.loads(line) for line in source_path.read_text(encoding="utf-8").splitlines() if line.strip())
    }
    rows = [json.loads(line) for line in output_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    nodes = [row["data"] for row in rows]
    validate(nodes)
    by_step = {node["step"]: node for node in nodes}
    report = json.loads((output / "_hindsight/reports" / relative.with_suffix(".json")).read_text())
    require(report["version"] == VERSION, "Output was generated by an older pipeline version")
    require(report["source_sha256"] == hashlib.sha256(source_path.read_bytes()).hexdigest(), "Source changed")
    for name, digest in report["artifacts"].items():
        require(hashlib.sha256((output / name).read_bytes()).hexdigest() == digest, f"Artifact changed: {name}")
    require(all(row["step"] == row["data"]["step"] for row in rows), "Envelope step mismatch")
    resolved = {episode.root: episode for episode in episodes(list(original.values())) if episode.terminal is not None}
    require({item["root"] for item in report["audits"]} == set(resolved), "Audit coverage mismatch")
    for item in report["audits"]:
        require(item["reviewed"] == item["initial_audit"]["untrustworthy"], "Missing independent review")
        require(not item["untrustworthy"] or item["reviewed"], "Unreviewed rejection")
    trusted, removed = prune(
        list(original.values()), {item["root"] for item in report["audits"] if item["untrustworthy"]}
    )
    require(removed == set(report["pruned_steps"]), "Pruning mismatch")
    surviving = [episode for episode in episodes(trusted) if episode.terminal is not None]
    expected_debug = {episode.root for episode in surviving if len(episode.steps) > 1}
    require({item["root"] for item in report["debug_rewrites"]} == expected_debug, "Debug coverage mismatch")
    terminals = {episode.terminal: episode for episode in surviving}
    expected_improve = set()
    for donor in surviving:
        root = original[donor.root]
        parent = next(iter(root.get("parents", [])), None)
        if root["operators_used"][0] == "improve" and parent in terminals:
            if better(original[donor.terminal], original[parent]):
                expected_improve.add((terminals[parent].root, donor.root))
    require(
        {(item["root"], item["donor_root"]) for item in report["improve_rewrites"]} == expected_improve,
        "Improve coverage mismatch",
    )
    additions = set()
    required_context = set()
    for stage, records in (("debug", report["debug_rewrites"]), ("improve", report["improve_rewrites"])):
        for record in records:
            require(len(record["added_steps"]) == 1, "Rewrite must be a single resolved proposal")
            step = record["added_steps"][0]
            require(step not in additions and step > max(original), "Synthetic step overlaps")
            additions.add(step)
            added = by_step[step]
            target, donor = resolved[record["root"]], resolved[record["donor_root"]]
            root, executed = original[target.root], original[donor.terminal]
            require(added["parents"] == root["parents"], "Source parent grouping changed")
            required_context.update(root["parents"])
            require(added["operators_used"] == root["operators_used"][:1], "Proposal operator changed")
            require(len(added["operators_metrics"]) == 1, "Copied original model calls")
            call = added["operators_metrics"][0]
            require(
                call["prompt_messages"] == root["operators_metrics"][0]["prompt_messages"], "Stored prompt changed"
            )
            require(call["usage"] == {}, "Synthetic response has misleading token usage")
            _, answer, block = parts(call["completion_text"])
            require(block.group("code").rstrip() == added["code"], "Generated code mismatch")
            require(added["plan"] == answer[: block.start()].strip(), "Generated plan lost")
            require(added["is_buggy"] is None, "Unexecuted rewrite has a bug verdict")
            for key in ("analysis", "term_out", "_term_out", "exit_code", "exec_time", "creation_time"):
                require(added.get(key) is None, f"Inherited execution record: {key}")
            for key in ("metric", "metric_maximize"):
                require(added[key] == executed[key], f"Inherited label changed: {key}")
            require(
                not any(
                    key in added
                    for key in ("metric_info/score", "metric_info/valid_submission", "metric_info/any_medal")
                ),
                "Inherited official execution results",
            )
            provenance = added["hindsight"]
            require(provenance["kind"] == "rewrite" and provenance["stage"] == stage, "Missing rewrite provenance")
            require(provenance["source_journal"] == str(relative), "Source journal mismatch")
            for field, steps in (("target_trajectory", target.steps), ("donor_trajectory", donor.steps)):
                require(
                    provenance[field] == [{"step": item, "id": original[item]["id"]} for item in steps],
                    f"Invalid {field}",
                )
            require(
                provenance["metric_source"] == {"step": donor.terminal, "id": executed["id"]},
                "Metric provenance mismatch",
            )
            require(provenance["response_origin"] == "regenerated", "Missing response origin")
            require(provenance["execution_status"] == "not_run", "Missing synthetic execution status")
            require(provenance["metric_origin"] == "inherited", "Missing inherited metric label")
            require(
                provenance["prompt_source"] == {"step": target.root, "id": root["id"]}, "Prompt provenance mismatch"
            )
            require(provenance["hint_includes_code"] == (report["hint_code"] == "include"), "Hint mode mismatch")
            cache_key = provenance["generation_cache_key"]
            cached = json.loads((output / "_hindsight/cache/regenerate" / f"{cache_key}.json").read_text())
            require(
                hashlib.sha256(json.dumps(cached["identity"], sort_keys=True).encode()).hexdigest() == cache_key,
                "Generation cache identity changed",
            )
            require(cached["result"]["model"] == provenance["generation_model"], "Generation model mismatch")
            require(cached["result"]["completion"] == call["completion_text"], "Full generated response changed")
            require(
                cached["identity"]["request"]["messages"]
                == inject_hint(
                    call["prompt_messages"],
                    record["hint"],
                    executed["code"] if provenance["hint_includes_code"] else None,
                ),
                "Generation prompt/hint mismatch",
            )
    pending = list(required_context)
    while pending:
        for parent in original[pending.pop()].get("parents", []):
            if parent not in required_context:
                required_context.add(parent)
                pending.append(parent)
    require(set(by_step) == additions | required_context, "Output contains originals or unused anchors")
    for step in required_context:
        node = by_step[step]
        require(
            not node["operators_used"] and not node["operators_metrics"], "Anchor has calls"
        )
        require(node["parents"] == original[step].get("parents", []), "Ancestor topology changed")
        require(node["code"] == "" and node["hindsight"]["kind"] == "context", "Anchor contains original code")
        require(
            node["hindsight"]["source_node"] == {"step": step, "id": original[step]["id"]}, "Anchor source mismatch"
        )
    for node in nodes:
        require(node["id"] not in {item["id"] for item in original.values()}, "Original node copied")
        require(
            sorted(node["children"]) == sorted(item["step"] for item in nodes if node["step"] in item["parents"]),
            "Children/parents mismatch",
        )
        if "current_best_node" in node:
            require(node["current_best_node"] in by_step, "Dangling current_best_node")
    run_dir = next(parent for parent in output_path.parents if (parent / "dojo_config.json").is_file())
    source_run = source / run_dir.relative_to(output)
    for name, digest in report["metadata_sha256"].items():
        require(
            hashlib.sha256((source_run / name).read_bytes()).hexdigest() == digest, f"Source metadata changed: {name}"
        )
        require((source_run / name).read_bytes() == (run_dir / name).read_bytes(), f"Run metadata changed: {name}")
    checkpoint = run_dir / "checkpoint/journal.jsonl"
    plain = read_nodes(checkpoint)
    require(len(plain) == len(nodes), "Checkpoint node count mismatch")
    for raw, flat in zip(nodes, plain):
        require(
            {key: value for key, value in raw.items() if not key.startswith("metric_info/") and key != "metric_info"}
            == {key: value for key, value in flat.items() if key != "metric_info"},
            "Checkpoint content mismatch",
        )
    run_meta = read_run_meta(run_dir)
    samples = list(iter_samples(checkpoint, run_meta, "verify"))
    big_samples = list(iter_big_samples(output_path, run_meta, "verify"))
    require(len(samples) == len(big_samples) == len(additions), "Downstream sample count mismatch")
    for plain_sample, big_sample in zip(samples, big_samples):
        for key in (
            "sample_id",
            "group_id",
            "prompt",
            "completion",
            "node_metric",
            "episode_metric",
            "episode_metric_reward",
            "episode_terminal_step",
        ):
            require(plain_sample[key] == big_sample[key], f"Reader mismatch: {key}")
        step = plain_sample["node_step"]
        require(plain_sample["episode_terminal_step"] == step, "Rewrite episode includes old debug nodes")
        require(plain_sample["episode_metric"] == by_step[step]["metric"], "Downstream CV mismatch")
        require(plain_sample["episode_metric_reward"] is not None, "Inherited metric reward missing")
        require(
            not plain_sample["node_has_result"] and plain_sample["node_is_buggy"] is None,
            "Synthetic execution fabricated",
        )
        require("hindsight" not in plain_sample and "hindsight" not in big_sample, "Tree metadata leaked")
        require(plain_sample["episode_score"] is None, "Synthetic official score fabricated")
    return {
        "journal": str(relative),
        "input_nodes": len(original),
        "output_nodes": len(nodes),
        "pruned_nodes": len(removed),
        "added_nodes": len(additions),
        "context_nodes": len(required_context),
        "debug_episodes_added": len(report["debug_rewrites"]),
        "improve_episodes_added": len(report["improve_rewrites"]),
        "downstream_samples": len(samples),
    }


def verify_all(source: Path, output: Path) -> dict:
    source, output = source.resolve(), output.resolve()
    paths = sorted(path.relative_to(source) for path in source.rglob("JOURNAL.jsonl"))
    require(bool(paths), "No input journals")
    require(
        sorted(path.relative_to(output) for path in output.rglob("JOURNAL.jsonl")) == paths, "Journal set mismatch"
    )
    records = [verify_journal(source, output, relative) for relative in paths]
    totals = {key: sum(record[key] for record in records) for key in records[0] if key != "journal"}
    result = {"journals": records, "totals": totals}
    atomic_json(output / "_hindsight/verification.json", result)
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    print(json.dumps(verify_all(args.input, args.output)["totals"], indent=2))


if __name__ == "__main__":
    main()
